def _rel(path: Path) -> str:
    return str(path.relative_to(ROOT)).replace("\\", "/")


def _copy_if_available(source: Path, destination: Path) -> str:
    if not source.exists():
        return "missing_source"
    destination.parent.mkdir(parents=True, exist_ok=True)
    if source.resolve(strict=False) != destination.resolve(strict=False):
        try:
            shutil.copy2(source, destination)
        except OSError as exc:
            if destination.exists():
                return f"kept_existing_{exc.__class__.__name__}"
            raise
    return "copied"


@dataclass(frozen=True)
class FigureAsset:
    figure_id: str
    role: str
    description_short: str
    source_stem: Path
    destination_dir: Path
    source_notebook: Path | None = None
    source_script: Path | None = None
    notes_code_only: str = ""

    @property
    def source_png(self) -> Path:
        return self.source_stem.with_suffix(".png")

    @property
    def source_pdf(self) -> Path:
        return self.source_stem.with_suffix(".pdf")

    @property
    def destination_png(self) -> Path:
        return self.destination_dir / f"{self.figure_id}.png"

    @property
    def destination_pdf(self) -> Path:
        return self.destination_dir / f"{self.figure_id}.pdf"


