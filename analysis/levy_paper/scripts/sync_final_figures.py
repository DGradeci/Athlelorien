SOURCE_DATA_PATTERNS = ("*.csv", "*.json", "*.md", "*.txt")


def _sync_figure_assets(assets: list[FigureAsset], generated_at: str) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for asset in assets:
        png_status = _copy_if_available(asset.source_png, asset.destination_png)
        pdf_status = _copy_if_available(asset.source_pdf, asset.destination_pdf)
        if png_status == "copied" and pdf_status == "copied":
            status = "copied"
        elif png_status == "missing_source" and pdf_status == "missing_source":
            status = "missing_source"
        else:
            status = f"partial_png_{png_status}_pdf_{pdf_status}"

        rows.append(
            {
                "figure_id": asset.figure_id,
                "role": asset.role,
                "description_short": asset.description_short,
                "png_path": _rel(asset.destination_png),
                "pdf_path": _rel(asset.destination_pdf),
                "source_png": _rel(asset.source_png),
                "source_pdf": _rel(asset.source_pdf),
                "source_notebook": _rel(asset.source_notebook) if asset.source_notebook else "",
                "source_script": _rel(asset.source_script) if asset.source_script else "",
                "status": status,
                "generated_at": generated_at,
                "notes_code_only": asset.notes_code_only,
            }
        )
    return rows


def _sync_source_data(generated_at: str) -> list[dict[str, str]]:
    SOURCE_DATA_DIR.mkdir(parents=True, exist_ok=True)
    rows: list[dict[str, str]] = []
    seen: set[Path] = set()
    for pattern in SOURCE_DATA_PATTERNS:
        for source in sorted(POLISHED_DIR.glob(pattern)):
            if source in seen or not source.is_file():
                continue
            seen.add(source)
            destination = SOURCE_DATA_DIR / source.name
            status = _copy_if_available(source, destination)
            rows.append(
                {
                    "file_name": source.name,
                    "path": _rel(destination),
                    "source_path": _rel(source),
                    "status": status,
                    "generated_at": generated_at,
                }
            )
    return rows


def _write_csv(path: Path, rows: list[dict[str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        return
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def _write_readme(generated_at: str, figure_rows: list[dict[str, str]]) -> None:
    main_count = sum(
        row["role"] == "main" and not row["status"].startswith("missing_source") for row in figure_rows
    )
    supp_count = sum(
        row["role"] == "supplementary" and not row["status"].startswith("missing_source") for row in figure_rows
    )
    README_PATH.write_text(
        "\n".join(
            [
                "# Levy Paper Figure Exports",
                "",
                "Use these folders for sharing current paper figures:",
                "",
                "- `main_figures/`: manuscript main figures plus retained candidate figures.",
                "- `supplementary_figures/`: supplementary and diagnostic figures.",
                "- `source_data/`: source CSVs, manifests, captions, and audit summaries for the current polished Figure 4/5 exports.",
                "",
                f"Last synced: `{generated_at}`.",
                f"Main manuscript figures copied: `{main_count}`.",
                f"Supplementary figures copied: `{supp_count}`.",
                "",
                "See `figure_manifest.csv` for the source file used for every exported figure.",
                "",
            ]
        ),
        encoding="utf-8",
    )


def sync_final_figures() -> tuple[list[dict[str, str]], list[dict[str, str]]]:
    generated_at = datetime.now().isoformat(timespec="seconds")
    FINAL_DIR.mkdir(parents=True, exist_ok=True)
    SUPPLEMENTARY_DIR.mkdir(parents=True, exist_ok=True)
    SOURCE_DATA_DIR.mkdir(parents=True, exist_ok=True)

    figure_rows = _sync_figure_assets(MAIN_FIGURES + SUPPLEMENTARY_FIGURES, generated_at)
    source_rows = _sync_source_data(generated_at)

    _write_csv(FIGURE_MANIFEST_PATH, figure_rows)
    _write_csv(FINAL_MANIFEST_PATH, [row for row in figure_rows if row["role"] == "main"])
    _write_csv(SOURCE_DATA_MANIFEST_PATH, source_rows)
    _write_readme(generated_at, figure_rows)
    return figure_rows, source_rows


